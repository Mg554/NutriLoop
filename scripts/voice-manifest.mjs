// voice-lines.json -> voice-ids.json (for synth.py) and, after synthesis,
// src/voiceClips.js listing the clips that exist.
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { clipId } from '../src/speechText.js'
const lines = JSON.parse(readFileSync('voice-lines.json', 'utf8'))
if (process.argv[2] === 'ids') {
  writeFileSync('voice-ids.json', JSON.stringify(Object.fromEntries(lines.map((l) => [l.key, clipId(l.key)]))))
} else {
  const have = lines.map((l) => clipId(l.key)).filter((id) => existsSync(`public/voice/${id}.mp3`))
  writeFileSync('src/voiceClips.js', `// Generated by scripts/voice-manifest.mjs (GitHub Action "Voice clips"). Do not edit.\nexport const VOICE = 'Piper ar_JO-kareem-medium'\nexport const CLIPS = new Set(${JSON.stringify([...new Set(have)].sort())})\n`)
  console.log('manifest:', have.length, 'clips')
}
